import { useAudioPlayer } from "expo-audio";
import { useFocusEffect } from "expo-router";
import { useCallback, useEffect } from "react";
import { Pressable, StyleSheet } from "react-native";

import {
    describeTransposition,
    formatTonic,
    formatTransposition,
    speakTonic,
} from "@/components/formatKey";
import { ThemedText } from "@/components/ThemedText";
import { justIntonationCents, transposePitch, type Pitch } from "@/core";

/**
 * Bundled samples, one per tonic, indexed by semitone above C, in equal temperament. They
 * ship inside the app, so the Pitch sounds offline. Each is a steady note that loops
 * seamlessly, so it can sound for as long as the button is held. Generated by
 * scripts/generate-pitch-samples.js.
 */
const SAMPLES = [
    require("@/assets/audio/pitch/00-C.wav"),
    require("@/assets/audio/pitch/01-Cs-Db.wav"),
    require("@/assets/audio/pitch/02-D.wav"),
    require("@/assets/audio/pitch/03-Ds-Eb.wav"),
    require("@/assets/audio/pitch/04-E.wav"),
    require("@/assets/audio/pitch/05-F.wav"),
    require("@/assets/audio/pitch/06-Fs-Gb.wav"),
    require("@/assets/audio/pitch/07-G.wav"),
    require("@/assets/audio/pitch/08-Gs-Ab.wav"),
    require("@/assets/audio/pitch/09-A.wav"),
    require("@/assets/audio/pitch/10-As-Bb.wav"),
    require("@/assets/audio/pitch/11-B.wav"),
];

/**
 * Sounds the Tag's Pitch, moved by the Transposition, for as long as it is held, like a
 * pitch pipe. A transposed Pitch is tuned as a pure interval from the Key's tonic. It shows
 * the tonic sounded and, in small text, the Transposition.
 *
 * The samples are steady notes, so every point in them sounds the same: a press plays from
 * wherever the last one paused, with nothing to rewind and nothing to wait for.
 */
export function PitchButton({ pitch: keyPitch, transposition }: { pitch: Pitch; transposition: number }) {
    const pitch = transposePitch(keyPitch, transposition);
    const player = useAudioPlayer(SAMPLES[pitch.semitone]);

    // Loop the steady sample for as long as the button is held, and tune it: play it a few cents
    // faster or slower, with pitch correction off so the pitch follows the speed (varispeed on
    // iOS). expo-audio 58 keeps both the speed and the tuning when a sample loops.
    useEffect(() => {
        // expo-audio has no loop or pitch options on creation; setting the properties is its
        // documented API.
        // eslint-disable-next-line react-hooks/immutability
        player.loop = true;
        player.shouldCorrectPitch = false;
        player.setPlaybackRate(2 ** (justIntonationCents(transposition) / 1200));
    }, [player, transposition]);

    // Leaving the Tag page mid-note stops the note.
    useFocusEffect(
        useCallback(
            () => () => {
                try {
                    player.pause();
                } catch {
                    // On unmount the player may already be released, and so already silent.
                }
            },
            [player],
        ),
    );

    return (
        <Pressable
            style={({ pressed }) => [styles.button, pressed && styles.pressed]}
            onPressIn={() => player.play()}
            onPressOut={() => player.pause()}
            accessibilityRole="button"
            accessibilityLabel={`Pitch: ${speakTonic(pitch.tonic)}, ${describeTransposition(transposition)}`}
            accessibilityHint="Sounds the note while held"
        >
            <ThemedText style={styles.text}>
                {formatTonic(pitch.tonic)}{" "}
                <ThemedText style={styles.transposition}>({formatTransposition(transposition)})</ThemedText>
            </ThemedText>
        </Pressable>
    );
}

const styles = StyleSheet.create({
    button: {
        minWidth: 80,
        alignItems: "center",
        justifyContent: "center",
        paddingHorizontal: 12,
    },
    pressed: {
        opacity: 0.7,
    },
    text: {
        color: "#fff",
        fontWeight: "600",
        userSelect: "none",
    },
    transposition: {
        color: "#fff",
        fontSize: 12,
        fontWeight: "400",
    },
});
